create or replace function public.audit_data_change()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  record_json jsonb;
  resolved_id bigint;
begin
  record_json := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  resolved_id := coalesce(
    nullif(record_json ->> 'id', '')::bigint,
    nullif(record_json ->> 'order_id', '')::bigint,
    nullif(record_json ->> 'customer_id', '')::bigint
  );
  insert into public.audit_logs (actor_id, action, entity_type, entity_id)
  values (auth.uid(), lower(tg_op), tg_table_name, resolved_id);
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

