create or replace function public.replace_usual_order_items(p_customer_id bigint, p_items jsonb)
returns void
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if jsonb_typeof(coalesce(p_items, '[]'::jsonb)) <> 'array' then
    raise exception 'items must be an array';
  end if;

  delete from public.usual_order_items where customer_id = p_customer_id;
  insert into public.usual_order_items (customer_id, product_id, quantity)
  select
    p_customer_id,
    (item ->> 'productId')::bigint,
    (item ->> 'quantity')::integer
  from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) item
  where (item ->> 'quantity')::integer > 0;
end;
$$;

create or replace function public.create_monthly_order(p_customer_id bigint, p_order_month text)
returns bigint
language plpgsql
set search_path = public, pg_temp
as $$
declare
  new_order_id bigint;
begin
  if p_order_month !~ '^\d{4}-(0[1-9]|1[0-2])$' then
    raise exception 'invalid order month';
  end if;

  insert into public.monthly_orders (customer_id, order_month)
  values (p_customer_id, p_order_month)
  on conflict (customer_id, order_month) do update set updated_at = now()
  returning id into new_order_id;

  insert into public.monthly_order_items
    (order_id, product_id, product_code_snapshot, product_name_snapshot, quantity)
  select new_order_id, usual.product_id, product.product_code, product.product_name, usual.quantity
  from public.usual_order_items usual
  join public.products product on product.id = usual.product_id
  where usual.customer_id = p_customer_id and product.is_active
  on conflict (order_id, product_id) do nothing;

  return new_order_id;
end;
$$;

create or replace function public.generate_monthly_orders(p_order_month text)
returns integer
language plpgsql
set search_path = public, pg_temp
as $$
declare
  affected integer;
begin
  if p_order_month !~ '^\d{4}-(0[1-9]|1[0-2])$' then
    raise exception 'invalid order month';
  end if;

  insert into public.monthly_orders (customer_id, order_month)
  select id, p_order_month from public.customers where is_active
  on conflict (customer_id, order_month) do nothing;
  get diagnostics affected = row_count;

  insert into public.monthly_order_items
    (order_id, product_id, product_code_snapshot, product_name_snapshot, quantity)
  select order_row.id, usual.product_id, product.product_code, product.product_name, usual.quantity
  from public.monthly_orders order_row
  join public.usual_order_items usual on usual.customer_id = order_row.customer_id
  join public.products product on product.id = usual.product_id
  where order_row.order_month = p_order_month and product.is_active
  on conflict (order_id, product_id) do nothing;

  return affected;
end;
$$;

create or replace function public.save_monthly_order(
  p_order_id bigint,
  p_status text,
  p_next_call_at timestamptz,
  p_delivery_date date,
  p_contact_note text,
  p_items jsonb
)
returns void
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if p_status not in ('draft', 'call_again', 'confirmed', 'skipped') then
    raise exception 'invalid order status';
  end if;
  if jsonb_typeof(coalesce(p_items, '[]'::jsonb)) <> 'array' then
    raise exception 'items must be an array';
  end if;

  update public.monthly_orders
  set status = p_status,
      next_call_at = p_next_call_at,
      delivery_date = p_delivery_date,
      contact_note = coalesce(p_contact_note, ''),
      confirmed_at = case when p_status = 'confirmed' then now() else null end
  where id = p_order_id;
  if not found then raise exception 'order not found'; end if;

  delete from public.monthly_order_items where order_id = p_order_id;
  insert into public.monthly_order_items
    (order_id, product_id, product_code_snapshot, product_name_snapshot, quantity)
  select
    p_order_id,
    product.id,
    product.product_code,
    product.product_name,
    (item ->> 'quantity')::integer
  from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) item
  join public.products product on product.id = (item ->> 'productId')::bigint
  where product.is_active and (item ->> 'quantity')::integer > 0;
end;
$$;

