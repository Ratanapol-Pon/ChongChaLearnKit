create table public.customers (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 160),
  phone text not null check (char_length(trim(phone)) between 1 and 40),
  address text not null check (char_length(trim(address)) between 1 and 500),
  map_url text not null default '' check (map_url = '' or map_url ~ '^https://'),
  preferred_call_day integer not null default 25 check (preferred_call_day between 1 and 31),
  preferred_delivery_day integer not null default 1 check (preferred_delivery_day between 1 and 31),
  notes text not null default '' check (char_length(notes) <= 1000),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index idx_customers_active_name on public.customers (is_active, name);

create table public.products (
  id bigint generated by default as identity primary key,
  product_code integer not null unique check (product_code between 1 and 10000000),
  product_name text not null check (char_length(trim(product_name)) between 1 and 200),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index idx_products_active_name on public.products (is_active, product_name);

create table public.usual_order_items (
  customer_id bigint not null references public.customers(id) on delete cascade,
  product_id bigint not null references public.products(id),
  quantity integer not null check (quantity between 1 and 1000000),
  primary key (customer_id, product_id)
);

create table public.monthly_orders (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers(id),
  order_month text not null check (order_month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  status text not null default 'draft' check (status in ('draft', 'call_again', 'confirmed', 'skipped')),
  next_call_at timestamptz,
  delivery_date date,
  contact_note text not null default '' check (char_length(contact_note) <= 1000),
  confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (customer_id, order_month)
);

create index idx_orders_month_status on public.monthly_orders (order_month, status);
create index idx_orders_delivery_date on public.monthly_orders (delivery_date);

create table public.monthly_order_items (
  order_id bigint not null references public.monthly_orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  product_code_snapshot integer not null check (product_code_snapshot between 1 and 10000000),
  product_name_snapshot text not null,
  quantity integer not null check (quantity between 1 and 1000000),
  primary key (order_id, product_id)
);

create table public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid,
  action text not null,
  entity_type text not null,
  entity_id bigint,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index idx_audit_entity on public.audit_logs (entity_type, entity_id);

